#!/usr/bin/env python3
# Assembles the mesh emulation test fixtures (the .spvasm beside this file: hand-written modules in the translator's task / mesh form, no game code) into
# memu_fixtures.h for t_android_memu.c. Run after changing a fixture: python3 dm/host/tests/memu/gen.py (needs spirv-as and spirv-val on the PATH)
import os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = [('mesh_tri', 'MEMU_MESH_TRI'), ('mesh_pts', 'MEMU_MESH_PTS'), ('task', 'MEMU_TASK'), ('fs_prim', 'MEMU_FS_PRIM')]


def main():
    out = ['// Generated by dm/host/tests/memu/gen.py from the .spvasm files beside it (spirv-as --target-env spv1.4). Do not edit', '#pragma once', '#include <stdint.h>']
    for name, sym in FIXTURES:
        src = os.path.join(HERE, name + '.spvasm')
        with tempfile.TemporaryDirectory() as td:
            spv = os.path.join(td, name + '.spv')
            subprocess.run(['spirv-as', '--target-env', 'spv1.4', '-o', spv, src], check=True)
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.3', spv], check=True)
            data = open(spv, 'rb').read()
        words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
        out.append('static const uint32_t %s[] = {' % sym)
        for i in range(0, len(words), 12):
            out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 12]) + ',')
        out.append('};')
    open(os.path.join(HERE, 'memu_fixtures.h'), 'w').write('\n'.join(out) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
